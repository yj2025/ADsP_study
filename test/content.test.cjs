const {DatabaseSync}=require('node:sqlite');
const {setupContent,readContent,parseCSV,parseFile,importContent}=require('../src/content-store.cjs');
const assert=require('node:assert/strict');
const fs=require('node:fs'),path=require('node:path'),os=require('node:os');
const {spawnSync}=require('node:child_process');
const db=new DatabaseSync(':memory:');db.exec('PRAGMA foreign_keys=ON');setupContent(db);
const count=()=>[db.prepare('SELECT count(*) n FROM content_lessons').get().n,db.prepare('SELECT count(*) n FROM content_questions').get().n];
const example=parseFile('content/example.json');
assert.deepEqual(count(),[3,6]);setupContent(db);assert.deepEqual(count(),[3,6]);
const before=readContent(db);assert.match(before.lessons[0].body,/<table>/);
assert.deepEqual(importContent(db,example,{dryRun:true}),{lessons:1,questions:1,dryRun:true});assert.deepEqual(count(),[3,6]);
importContent(db,example);assert.deepEqual(count(),[4,7]);assert.equal(readContent(db).questions[6].lesson,3);
assert.throws(()=>importContent(db,example),/중복 ID/);assert.deepEqual(count(),[4,7]);
const csv=parseFile('content/example.csv');assert.equal(csv.questions[0].answer,0);assert.match(csv.lessons[0].body,/\n/);
importContent(db,csv);assert.deepEqual(count(),[5,8]);
const baseQuestion={...example.questions[0],id:'invalid-question'};
assert.throws(()=>importContent(db,{questions:[{...baseQuestion,lesson_id:'missing'}]}),/존재하지 않는/);
assert.throws(()=>importContent(db,{questions:[{...baseQuestion,answer:4}]}),/answer/);
assert.throws(()=>importContent(db,{questions:[{...baseQuestion,options:['a','a','b','c']}]}),/중복 보기/);
assert.throws(()=>importContent(db,{lessons:[{id:'new-lesson',title:'test',body:'test'}],questions:[{...baseQuestion,answer:9}]}),/answer/);assert.deepEqual(count(),[5,8]);
assert.throws(()=>importContent(db,{lessons:[{id:'repeat',title:'a',body:'b'},{id:'repeat',title:'a',body:'b'}]}),/중복 ID/);
assert.throws(()=>importContent(db,{lessons:[{id:'bad-html',title:'a',body:'b',body_format:'html'}]}),/알 수 없는 필드/);
assert.throws(()=>importContent(db,{lessons:[{id:'bad-url',title:'a',body:'b',source_url:'javascript:alert(1)'}]}),/HTTP/);
assert.throws(()=>parseCSV('type,id\nlesson,"unclosed'),/닫히지/);
assert.throws(()=>parseCSV('type,id\nlesson,"a"x'),/구분자/);
assert.throws(()=>parseCSV('type,id,id\nlesson,a,b'),/중복/);
assert.throws(()=>parseCSV('type,id\nlesson,a,extra'),/열 개수/);
assert.throws(()=>parseCSV('type,id\nunknown,a'),/type/);
const quoted=parseCSV('\uFEFFtype,id,title,body\r\nlesson,quoted,"쉼표, 제목","한 줄\n두 줄 ""인용"""\r\n');assert.equal(quoted.lessons[0].body,'한 줄\n두 줄 "인용"');
importContent(db,{lessons:[{id:'literal-html',title:'<img src=x onerror=alert(1)>',body:'<script>alert(1)</script>'}],questions:[{...baseQuestion,id:'literal-q',lesson_id:'literal-html',text:'<script>x</script>'}]});
const safe=readContent(db);assert.ok(!safe.lessons.at(-1).body.includes('<script>'));assert.match(safe.lessons.at(-1).title,/&lt;img/);assert.match(safe.questions.at(-1).text,/&lt;script/);
const previous=count();db.exec("CREATE TRIGGER fail_question BEFORE INSERT ON content_questions BEGIN SELECT RAISE(ABORT, 'test rollback'); END;");
assert.throws(()=>importContent(db,{lessons:[{id:'rollback-lesson',title:'a',body:'b'}],questions:[{...baseQuestion,id:'rollback-question',lesson_id:'rollback-lesson'}]}),/test rollback/);assert.deepEqual(count(),previous);db.close();
const folder=fs.mkdtempSync(path.join(os.tmpdir(),'adsp-content-'));
try{
const database=path.join(folder,'study.sqlite');
const cli=(...args)=>spawnSync(process.execPath,['scripts/import-content.cjs','content/example.json','--database',database,...args],{encoding:'utf8'});
assert.equal(cli('--dry-run').status,0);assert.equal(fs.existsSync(database),false);
assert.equal(cli().status,0);let stored=new DatabaseSync(database);assert.equal(stored.prepare('SELECT count(*) n FROM content_lessons').get().n,4);stored.close();
assert.equal(cli('--dry-run').status,1);assert.equal(cli().status,1);
stored=new DatabaseSync(database);assert.equal(stored.prepare('SELECT count(*) n FROM content_questions').get().n,7);stored.close();
}finally{fs.rmSync(folder,{recursive:true,force:true});}
console.log('PASS: seed migration, JSON/CSV, BOM/quotes/newlines, duplicate IDs, invalid references/answers, atomic rollback, dry-run, CLI persistence, safe HTML rendering');
